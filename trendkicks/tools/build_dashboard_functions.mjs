import { mkdir, readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const read = (path) => readFile(new URL(path, root), "utf8");
const output = new URL("docs/deploy/", root);
await mkdir(output, { recursive: true });

// Only inline these known local imports; preserve the external Supabase import.
const stripSharedImports = (source) =>
  source.replace(
    /^import\s+(?:type\s+)?\{[^}]*\}\s+from\s+"(?:\.\.\/_shared\/(?:runtime|payment_rules|review_image|push_delivery)|\.\/payment_rules)\.ts";\s*/gm,
    "",
  );
const rules = await read("supabase/functions/_shared/payment_rules.ts");
const runtime = stripSharedImports(
  await read("supabase/functions/_shared/runtime.ts"),
);
for (
  const name of [
    "create-invoice",
    "xendit-webhook",
    "upload-review-photo",
    "store-jobs",
  ]
) {
  const handler = stripSharedImports(
    await read(`supabase/functions/${name}/index.ts`),
  );
  const helper = name === "upload-review-photo"
    ? await read("supabase/functions/_shared/review_image.ts")
    : name === "store-jobs"
    ? await read("supabase/functions/_shared/push_delivery.ts")
    : "";
  const bundled =
    `// Generated by node tools/build_dashboard_functions.mjs\n// Paste this entire file into the Supabase Edge Function named ${name}.\n// Edit the original files under supabase/functions, then regenerate this copy.\n\n${rules}\n${runtime}\n${helper}\n${handler}`;
  if (/from\s+["']\.{1,2}\//.test(bundled)) {
    throw new Error(`Unresolved local import in ${name}`);
  }
  await writeFile(new URL(`${name}.ts`, output), bundled);
  console.log(`Created docs/deploy/${name}.ts`);
}
